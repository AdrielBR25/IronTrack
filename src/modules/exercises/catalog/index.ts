/** Catálogo padrão (montado uma vez, no primeiro uso). */
export function getCatalog(): readonly CatalogExercise[] {
  return (cache ??= Object.freeze(build()));
}

/** Entrada do catálogo pelo ID (índice montado uma vez). */
export function catalogById(id: string): CatalogExercise | undefined {
  return (byId ??= new Map(getCatalog().map((c) => [c.catalogId, c]))).get(id);
}
